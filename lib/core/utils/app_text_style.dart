TextStyle size24TextStyle({Color? textColor, FontWeight? fontWeight}) {
  return GoogleFonts.manrope(
    textStyle: TextStyle(
      color: textColor ?? AppColors.whiteColor,
      fontSize: 24.sp,
      fontWeight: fontWeight ?? FontWeight.w400,
    ),
  );
}

